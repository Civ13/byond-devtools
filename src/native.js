/**
 * Native BYOND harness (Node adapter). Builds a throwaway project that declares stub types for
 * every path a map uses, compiles it with a separately installed DreamMaker, boots it headless
 * in DreamDaemon with -safe, and reads back a JSON dump of the loaded world.
 *
 * Nothing here downloads BYOND, touches a game checkout or contacts a server. The caller passes
 * the BYOND bin directory explicitly. Work happens in a fresh temporary directory.
 */
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { overrideKeys, overrideAssignments } from './world.js';

// Built-in vars of /atom, /atom/movable, /mob, /turf and /area in BYOND 516. Overrides of these
// need no declaration; any other override key is declared on /atom so the stub project compiles.
export const BUILTIN_VARS = new Set(`alpha appearance appearance_flags blend_mode color contents density desc dir filters
gender icon icon_state icon_w icon_z invisibility infra_luminosity layer luminosity maptext maptext_width maptext_height
maptext_x maptext_y mouse_over_pointer mouse_drag_pointer mouse_drop_pointer mouse_drop_zone mouse_opacity name opacity
overlays override pixel_w pixel_x pixel_y pixel_z plane render_source render_target suffix text type underlays
vis_contents vis_flags vis_locs verbs x y z loc locs tag parent_type vars animate_movement bound_height bound_width
bound_x bound_y glide_size particles screen_loc step_size step_x step_y ckey client group key see_in_dark see_infrared
see_invisible sight`.split(/\s+/));
const ROOTS = new Set(['atom', 'turf', 'area', 'obj', 'mob', 'datum', 'image', 'sound', 'icon', 'matrix', 'list']);

/** Type paths used by the map: placed atoms plus path literals inside override text (outside strings). */
export function mapTypePaths(map) {
  const paths = new Set();
  for (const d of map.definitions) for (const a of d.atoms) {
    paths.add(a.path);
    if (!a.overridesRaw) continue;
    const unquoted = a.overridesRaw.replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, '""');
    for (const m of unquoted.matchAll(/(?<![\w/])\/([A-Za-z_]\w*)(?:\/[A-Za-z_]\w*)*/g)) if (ROOTS.has(m[1])) paths.add(m[0]);
  }
  return [...paths].sort();
}

const dmString = s => '"' + s.replace(/[\\"\[\]]/g, c => '\\' + c) + '"';

/** DM source for the stub project. `mapFile` is the map's file name inside the project folder. */
export function harnessSource(map, mapFile, { resourceRoot } = {}) {
  const types = mapTypePaths(map).filter(p => !['/atom', '/turf', '/area', '/obj', '/mob', '/datum'].includes(p));
  const keys = overrideKeys(map), all = new Set();
  for (const d of map.definitions) for (const a of d.atoms) for (const o of overrideAssignments(a.overridesRaw)) all.add(o.key);
  const declared = [...all].sort().filter(k => !BUILTIN_VARS.has(k));
  return `// Generated by byond-devtools native harness. Throwaway project; do not edit.
${resourceRoot ? `#define FILE_DIR ${dmString(resourceRoot.split(path.sep).join('/'))}\n` : ''}${declared.map(k => `/atom/var/${k}`).join('\n')}
${types.join('\n')}
#include ${dmString(mapFile)}
/world/loop_checks = 0
/proc/devtools_vars(atom/A, list/keys)
	var/list/out = list()
	for(var/k in keys)
		out += (k in A.vars) ? "[A.vars[k]]" : null
	return out
/world/New()
	..()
	var/list/keys = list(${keys.map(dmString).join(', ')})
	var/list/cells = list()
	for(var/z in 1 to world.maxz)
		for(var/y in 1 to world.maxy)
			for(var/x in 1 to world.maxx)
				var/turf/T = locate(x, y, z)
				var/list/contents = list()
				for(var/atom/movable/A in T.contents)
					if(A.loc != T)
						continue // step/bounds offsets also list a movable in neighbouring turfs
					contents += list(list("[A.type]", devtools_vars(A, keys)))
				cells += list(list("[T.type]", "[T.loc.type]", length(T.underlays), devtools_vars(T, keys), contents))
	text2file(json_encode(list("byond" = "[world.byond_version].[world.byond_build]", "maxx" = world.maxx, "maxy" = world.maxy, "maxz" = world.maxz, "keys" = keys, "cells" = cells)), "devtools_dump.json")
	shutdown()
`;
}

function tool(binDir, name) {
  const exe = process.platform === 'win32' ? (name === 'DreamMaker' ? 'dm.exe' : 'dd.exe') : name;
  return path.join(binDir, exe);
}

/**
 * Compile and boot `mapText` natively. Returns {status:'ok', dump, compiler} or
 * {status:'compile-failed'|'run-failed', compiler, runtime}. Never throws for BYOND failures.
 */
export async function recordNative(map, mapText, { binDir, resourceRoot, timeoutMs = 120000, keep = false } = {}) {
  if (!binDir) throw new Error('binDir (BYOND bin directory) is required');
  const dir = await mkdtemp(path.join(os.tmpdir(), 'byond-native-'));
  try {
    await writeFile(path.join(dir, 'map.dmm'), mapText);
    await writeFile(path.join(dir, 'harness.dme'), harnessSource(map, 'map.dmm', { resourceRoot }));
    const env = { ...process.env, LD_LIBRARY_PATH: [binDir, process.env.LD_LIBRARY_PATH].filter(Boolean).join(path.delimiter) };
    const compile = spawnSync(tool(binDir, 'DreamMaker'), ['-clean', '-max_errors', '0', 'harness.dme'], { cwd: dir, env, encoding: 'utf8', timeout: timeoutMs, killSignal: 'SIGKILL' });
    const compiler = `${compile.stdout || ''}${compile.stderr || ''}${compile.error ? String(compile.error) : ''}`;
    if (compile.status !== 0 || !/ 0 errors/.test(compiler)) return { status: / \d+ errors?/.test(compiler) ? 'compile-failed' : 'compiler-crashed', compiler };
    const run = spawnSync(tool(binDir, 'DreamDaemon'), ['harness.dmb', '-safe', '-invisible', '-quiet'], { cwd: dir, env, encoding: 'utf8', timeout: timeoutMs, killSignal: 'SIGKILL' });
    const runtime = `${run.stdout || ''}${run.stderr || ''}${run.error ? String(run.error) : ''}`;
    let text;
    try { text = await readFile(path.join(dir, 'devtools_dump.json'), 'utf8'); } catch { return { status: 'run-failed', compiler, runtime }; }
    return { status: 'ok', dump: JSON.parse(text), compiler, runtime, dir: keep ? dir : undefined };
  } finally { if (!keep) await rm(dir, { recursive: true, force: true }); }
}

/**
 * Instantiate `types` from a fixture project natively and read `vars` from each instance.
 * Only for fixture projects: it runs their New() procs. Returns {byond, types:{path:{var:value}}}.
 */
export async function recordInstanceVars({ root, dme, types, vars, binDir, timeoutMs = 120000 }) {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'byond-values-'));
  try {
    const posix = p => p.split(path.sep).join('/');
    await writeFile(path.join(dir, 'probe.dme'), `#define FILE_DIR ${dmString(posix(path.resolve(root)))}
#include ${dmString(posix(path.resolve(root, dme)))}
/world/maxx = 1
/world/maxy = 1
/world/maxz = 1
/world/New()
	var/list/out = list()
	for(var/T in list(${types.join(', ')}))
		var/datum/D
		try
			D = ispath(T, /turf) ? new T(locate(1, 1, 1)) : new T
		catch(var/exception/e)
			out["[T]"] = "error: [e]"
			continue
		var/list/row = list()
		for(var/v in list(${vars.map(dmString).join(', ')}))
			row[v] = (v in D.vars) ? (isicon(D.vars[v]) || isfile(D.vars[v]) ? "[D.vars[v]]" : D.vars[v]) : null
		out["[T]"] = row
	text2file(json_encode(list("byond" = "[world.byond_version].[world.byond_build]", "types" = out)), "values.json")
	shutdown()
/world/Error(exception/e)
	text2file("runtime: [e]", "errors.txt")
`);
    const env = { ...process.env, LD_LIBRARY_PATH: [binDir, process.env.LD_LIBRARY_PATH].filter(Boolean).join(path.delimiter) };
    const c = spawnSync(tool(binDir, 'DreamMaker'), ['-clean', 'probe.dme'], { cwd: dir, env, encoding: 'utf8', timeout: timeoutMs, killSignal: 'SIGKILL' });
    if (!/ 0 errors/.test(c.stdout || '')) throw new Error(`fixture compile failed: ${c.stdout}${c.stderr}`);
    spawnSync(tool(binDir, 'DreamDaemon'), ['probe.dmb', '-safe', '-invisible', '-quiet'], { cwd: dir, env, encoding: 'utf8', timeout: timeoutMs, killSignal: 'SIGKILL' });
    return JSON.parse(await readFile(path.join(dir, 'values.json'), 'utf8'));
  } finally { await rm(dir, { recursive: true, force: true }); }
}

/**
 * Ask DreamDaemon for icon pixels with icon.GetPixel. `files` maps a DMI path (readable by the
 * caller) to queries [{state, dir, frame, moving, x, y}] where x/y are 1-based from the top-left.
 * Files are copied into the temp project, so DreamDaemon runs with -safe and reads nothing else.
 * Returns {byond, results: {path: [colour text | null]}}.
 */
export async function recordIconPixels({ files, binDir, timeoutMs = 300000 }) {
  const { copyFile } = await import('node:fs/promises');
  const dir = await mkdtemp(path.join(os.tmpdir(), 'byond-pixels-'));
  try {
    const plan = [];
    let n = 0;
    for (const [source, queries] of Object.entries(files)) {
      const local = `icon${n++}.dmi`; await copyFile(source, path.join(dir, local));
      plan.push({ source, local, queries });
    }
    await writeFile(path.join(dir, 'queries.json'), JSON.stringify(plan.map(p => ({ file: p.local, q: p.queries.map(q => [q.state, q.dir, q.frame, q.moving ? 1 : 0, q.x, q.y]) }))));
    await writeFile(path.join(dir, 'probe.dme'), `/world/New()
	var/list/plan = json_decode(file2text("queries.json"))
	var/list/out = list()
	for(var/list/entry in plan)
		var/icon/I = icon(file(entry["file"]))
		var/list/row = list()
		var/height = I.Height()
		for(var/list/q in entry["q"])
			row += I.GetPixel(q[5], height - q[6] + 1, q[1], q[2], q[3], q[4] ? 1 : 0)
		out += list(row)
	text2file(json_encode(list("byond" = "[world.byond_version].[world.byond_build]", "results" = out)), "pixels.json")
	shutdown()
`);
    const env = { ...process.env, LD_LIBRARY_PATH: [binDir, process.env.LD_LIBRARY_PATH].filter(Boolean).join(path.delimiter) };
    const c = spawnSync(tool(binDir, 'DreamMaker'), ['-clean', 'probe.dme'], { cwd: dir, env, encoding: 'utf8', timeout: timeoutMs, killSignal: 'SIGKILL' });
    if (!/ 0 errors/.test(c.stdout || '')) throw new Error(`pixel probe compile failed: ${c.stdout}${c.stderr}`);
    const r = spawnSync(tool(binDir, 'DreamDaemon'), ['probe.dmb', '-safe', '-invisible', '-quiet'], { cwd: dir, env, encoding: 'utf8', timeout: timeoutMs, killSignal: 'SIGKILL' });
    let text; try { text = await readFile(path.join(dir, 'pixels.json'), 'utf8'); } catch { throw new Error(`pixel probe produced no output: ${r.stdout}${r.stderr}`); }
    const dump = JSON.parse(text);
    return { byond: dump.byond, results: Object.fromEntries(plan.map((p, i) => [p.source, dump.results[i]])) };
  } finally { await rm(dir, { recursive: true, force: true }); }
}
